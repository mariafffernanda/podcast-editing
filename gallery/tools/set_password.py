"""Sets one page's password. Writes only a keyed hash to data/access.js; the password is never stored or printed.

usage:  COOKIE_SECRET=... python3 tools/set_password.py <guest-slug | owner>
The secret must be the same one saved in Vercel (Settings > Environment Variables > COOKIE_SECRET).
"""
import getpass
import hashlib
import hmac
import json
import os
import re
import sys
import unicodedata
from pathlib import Path

ACCESS = Path(__file__).resolve().parent.parent / "data/access.js"


def norm(p: str) -> str:  # same as norm() in middleware.js
    p = unicodedata.normalize("NFD", p.strip().lower())
    return re.sub(r"\s+", "", "".join(c for c in p if unicodedata.category(c) != "Mn"))


def keyed(secret: str, page: str, pw: str) -> str:
    return hmac.new(secret.encode(), f"pw:{page}:{norm(pw)}".encode(), hashlib.sha256).hexdigest()


def load() -> dict:
    m = re.search(r"export default (\{.*\});", ACCESS.read_text(), re.S) if ACCESS.exists() else None
    return json.loads(m.group(1)) if m else {}


def save(d: dict) -> None:
    ACCESS.write_text("// Generated by tools/set_password.py. Keyed hashes only: the passwords are never stored anywhere.\n"
                      "export default " + json.dumps(d, indent=1, sort_keys=True) + ";\n")


if __name__ == "__main__":
    secret = os.environ.get("COOKIE_SECRET")
    if not secret:
        sys.exit("Set COOKIE_SECRET first (the same value as in Vercel).")
    page = sys.argv[1]
    pw = getpass.getpass(f"Password for {page}: ")
    if len(norm(pw)) < 6:
        sys.exit("Use at least 6 letters or numbers.")
    d = load(); d[page] = keyed(secret, page, pw); save(d)
    print(f"saved the hash for {page}. Commit data/access.js and push.")
